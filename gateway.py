"""APG Platform API Gateway — capability discovery and health aggregation.

Container entrypoint for ``Dockerfile.gateway``. Previously this file was
generated by a heredoc inside the Dockerfile, which meant it was unreviewed,
unlinted, and invisible to the type checker. It is tracked here instead.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

from flask import Flask, jsonify

app = Flask(__name__)

_MANIFEST_PATH = Path(__file__).parent / "capabilities" / "MANIFEST.json"
with _MANIFEST_PATH.open(encoding="utf-8") as fh:
	MANIFEST: dict[str, Any] = json.load(fh)


@app.get("/health")
def health() -> tuple[dict[str, Any], int]:
	return {"status": "ok", "gateway": "apg-platform", "capabilities": MANIFEST["capability_count"]}, 200


@app.get("/capabilities")
def list_caps() -> tuple[dict[str, Any], int]:
	return {"capabilities": list(MANIFEST["capabilities"].keys()), "count": MANIFEST["capability_count"]}, 200


@app.get("/capabilities/<cap_id>")
def get_cap(cap_id: str) -> tuple[dict[str, Any], int] | tuple[dict[str, str], int]:
	cap = MANIFEST["capabilities"].get(cap_id)
	if not cap:
		return {"error": "not_found"}, 404
	return cap, 200


@app.get("/domains")
def domains() -> tuple[dict[str, Any], int]:
	return MANIFEST["by_domain"], 200


if __name__ == "__main__":
	app.run(host="0.0.0.0", port=int(os.environ.get("GATEWAY_PORT", "8000")))